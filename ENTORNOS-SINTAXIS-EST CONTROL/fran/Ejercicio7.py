
'''Ejercicio 7. Mayor de edad

Solicita la edad de una persona.

Muestra:

Eres mayor de edad

o:

Eres menor de edad
'''

edad = int(input('Dime tu edad  '))

if edad >= 18:

    print(f"Eres mayor de edad, porque tienes: {edad} años")

else:
    
    print(f"Eres menor de edad, porque tienes: {edad} años")    
    

